"""Write docs/megaglest-units-catalog.md: every unit of the MegaGlest faction(s) on disk with its models, animations and textures.
LICENCE: GPL-3.0 (the data described is MegaGlest's, CC BY-SA 3.0)."""
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

from PIL import Image

from scripts.g3d import parse_g3d
from scripts.glest_export import parse_skills, playback_fps

LOOP = {"stop", "move", "attack"}


def unit_row(unit_dir: Path):
    xml = unit_dir / f"{unit_dir.name}.xml"
    if not xml.exists():
        return None
    skills = []
    textures, tris, verts = set(), 0, 0
    for sk in parse_skills(xml):
        for rel in sk["paths"]:
            m = parse_g3d((unit_dir / rel).read_bytes())
            frames = max(me.frame_count for me in m.meshes)
            looping = sk["type"] in LOOP
            skills.append((sk["type"], Path(rel).name, frames, sk["anim_speed"], playback_fps(frames, sk["anim_speed"], looping),
                           [me.vertices.shape[1] for me in m.meshes]))
            for me in m.meshes:
                if me.diffuse_texture:
                    textures.add(me.diffuse_texture)
    st = next((s for s in skills if s[0] == "stop"), skills[0])
    verts = sum(st[5])
    tris = sum(len(parse_g3d((unit_dir / "models" / st[1]).read_bytes()).meshes[i].indices) // 3 for i in range(len(st[5])))
    tex = []
    for t in sorted(textures):
        p = unit_dir / "models" / t
        tex.append(f"{t} ({Image.open(p).size[0]}x{Image.open(p).size[1]})" if p.exists() else t)
    sounds = len(list((unit_dir / "sounds").glob("*"))) if (unit_dir / "sounds").exists() else 0
    return {"name": unit_dir.name, "skills": skills, "verts": verts, "tris": tris, "tex": tex, "sounds": sounds,
            "images": len(list((unit_dir / "images").glob("*"))) if (unit_dir / "images").exists() else 0}


def main(factions_dir: Path, out: Path):
    lines = ["# MegaGlest unit models on disk", "",
             "Generated by `scripts/megaglest_catalog.py` from the official MegaGlest data (`techs/megapack/factions/*/units/*`, "
             "CC BY-SA 3.0). Frames and speeds are read from the `.g3d` and `.xml` files; playback fps = frames x anim-speed / 100 "
             "(die: (frames - 1) x anim-speed / 100). All of them are vertex-morph models with no skeleton, like DK2's KMF.", "",
             "Only the **magic** faction is downloaded here. Your own `mg.zip` holds tilesets (trees, rocks, ...) and no factions, "
             "so the other MegaGlest factions are not catalogued yet.", ""]
    rows = []
    for f in sorted(p for p in Path(factions_dir).iterdir() if p.is_dir()):
        for u in sorted((f / "units").iterdir()):
            try:
                r = unit_row(u)
            except Exception as e:                                   # a unit without animations (a tower, say)
                r = None
                print("skip", u.name, e, file=sys.stderr)
            if r:
                rows.append((f.name, r))
    lines += ["| Faction | Unit | Vertices | Triangles | Animations (frames @ fps) | Textures | Sounds |", "|---|---|---|---|---|---|---|"]
    for fac, r in rows:
        an = "; ".join(f"{s[0]} {s[2]}f @ {s[4]:.1f}" for s in r["skills"])
        lines.append(f"| {fac} | **{r['name']}** | {r['verts']} | {r['tris']} | {an} | {', '.join(r['tex'])} | {r['sounds']} |")
    lines += ["", "## Per unit, in detail", ""]
    for fac, r in rows:
        lines += [f"### {r['name']}", "", f"{r['verts']} vertices, {r['tris']} triangles (standing model), textures: {', '.join(r['tex'])}, "
                  f"{r['sounds']} sound files.", "", "| Skill | File | Mesh parts (vertices) | Frames | anim-speed | fps |", "|---|---|---|---|---|---|"]
        for s in r["skills"]:
            lines.append(f"| {s[0]} | {s[1]} | {' + '.join(map(str, s[5]))} | {s[2]} | {s[3]:g} | {s[4]:.1f} |")
        lines.append("")
    lines += ["## What is built into the viewer", "",
              "- **Golem**: native stand/walk/attack/die/construction plus DK2 Giant-driven clips and sounds.",
              "- **Battlemage**: native stand/walk/attack/morph/die plus DK2 Priest/Dark Elf-driven clips and sounds.",
              "- **Behemoth**: native stand/walk/attack/die plus DK2 Giant-driven clips and sounds (the base for the custom creature).",
              "- **wicker_behemoth** is a separate, different unit (a wicker giant) with its own models; it is not the Behemoth.", ""]
    Path(out).write_text("\n".join(lines))
    print(len(rows), "units ->", out)


if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(sys.argv[2]))
